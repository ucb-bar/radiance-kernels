#!/usr/bin/env python3
"""memlat data: the pointer chains the chaser follows (one region1 blob, memlat_data.h gives the layout).

A node is one 64 B line whose first word is the GPU address of the next node.  Every (cluster, level, pattern) has its
own chain of WARM + N + 1 nodes on lines nothing else touches, so every timed load misses the caches:
  seq   node i at seg + 64 i                       (consecutive lines: DRAM row hits)
  rand  WARM + N + 1 distinct lines drawn at random from a 1 MiB segment, in random order   (row misses)
Per cluster: 4 seq segments of 256 KiB, then 4 rand segments of 1 MiB (5 MiB); cluster c at REG1 + c * 5 MiB.
MEMLAT_CHECK_C<c> is the XOR of the chaser's final pointers (kernel.cpp: chase order), checked by the host.
"""
import os
import numpy as np

N, WARM, SMALL = 2048, 64, 256       # timed loads per chase, untimed warm-up loads, the small (cached) chain
LEVELS, CLUSTERS = 4, 2
LINE, SEQ_SEG, RAND_SEG = 64, 256 << 10, 1 << 20
CL_SPAN = LEVELS * (SEQ_SEG + RAND_SEG)
REG1 = 0x20000000
T = WARM + N + 1                     # nodes per chain
rng = np.random.default_rng(7)

blob = np.zeros(CLUSTERS * CL_SPAN // 4, np.uint32)


def put_chain(off, lines):
    """chain over the lines (64 B units) of the segment at blob byte offset off; returns its node addresses"""
    addr = REG1 + off + LINE * np.asarray(lines, np.int64)
    blob[(off + LINE * np.asarray(lines[:-1], np.int64)) // 4] = addr[1:]
    blob[(off + LINE * int(lines[-1])) // 4] = addr[0]           # the last node points back to the head
    return [int(a) for a in addr]


heads, check = {}, {}
for c in range(CLUSTERS):
    x = 0
    for lv in range(LEVELS):
        seq = put_chain(c * CL_SPAN + lv * SEQ_SEG, np.arange(T))
        rnd = put_chain(c * CL_SPAN + LEVELS * SEQ_SEG + lv * RAND_SEG,
                        rng.choice(RAND_SEG // LINE, T, replace=False))
        heads[c, lv] = (seq[0], rnd[0])
        x ^= seq[WARM + N] ^ rnd[WARM + N]
        if lv == 0:   # level 0 also re-chases its seq chain (warm) and twice the first SMALL nodes (small)
            x ^= seq[WARM + N] ^ seq[SMALL] ^ seq[SMALL]
    check[c] = x

os.makedirs("data", exist_ok=True)
blob.tofile("data/memlat.region1.bin")
with open("memlat_data.h", "w") as f:
    f.write("#pragma once\n// generated by gen_data.py\n")
    f.write(f"#define MEMLAT_N {N}u\n#define MEMLAT_WARM {WARM}u\n#define MEMLAT_SMALL {SMALL}u\n"
            f"#define MEMLAT_LEVELS {LEVELS}u\n")
    for c in range(CLUSTERS):
        f.write(f"#define MEMLAT_CHECK_C{c} 0x{check[c]:08x}u\n")
    f.write("static const unsigned memlat_heads[%d][%d][2] = {\n" % (CLUSTERS, LEVELS))
    for c in range(CLUSTERS):
        f.write("  {" + ", ".join("{0x%08xu, 0x%08xu}" % heads[c, lv] for lv in range(LEVELS)) + "},\n")
    f.write("};\n")
print(f"region1 {blob.nbytes >> 20} MiB, chains of {T} nodes")
